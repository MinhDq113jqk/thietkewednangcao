const assert = require('node:assert/strict');
const crypto = require('node:crypto');

async function verifyCommercialFixesUI({ page, database, context, apiUrl, accounts, shopId, goto, login, logout, bearer, screenshot, passed }) {
  const tokens = {};
  for (const role of ['buyer', 'seller', 'admin']) tokens[role] = await bearer(accounts[role]);
  const request = async (route, data, role = 'admin', method = 'post', status = 201) => {
    const response = await context.request[method](`${apiUrl}/api/${route}`, { headers: { Authorization: `Bearer ${tokens[role]}`, 'Idempotency-Key': crypto.randomUUID() }, data });
    const body = await response.json();
    assert.equal(response.status(), status, `${method} ${route}: ${body.error?.code || body.message || ''}`);
    return body;
  };
  const product = await request('seller/products', { name: 'CommercialUI Cup', category: 'Gốm sứ', price: 200000, salePrice: 100000, stock: 10 }, 'seller');
  await request('seller/products', { name: 'CommercialUI Bowl', category: 'Gốm sứ', price: 120000, stock: 10 }, 'seller');
  const checkout = async quantity => {
    const items = [{ productId: product.id, quantity }];
    const quote = await request('shipping/estimate', { city: 'Hà Nội', items }, 'buyer', 'post', 200);
    return request('orders', { items, paymentMethod: 'cod', quoteFingerprint: quote.fingerprint,
      shippingAddress: { name: 'Synthetic UI buyer', phone: '0900000000', address: '1 Fixture Street', city: 'Hà Nội' } }, 'buyer');
  };
  const stock = async () => (await database.query('SELECT stock,"stockVersion" FROM products WHERE id=$1', [product.id])).rows[0];
  await login(accounts.seller);
  let releaseProducts;
  const productGate = new Promise(resolve => { releaseProducts = resolve; });
  const productDetailPattern = `**/api/seller/products/${product.id}`;
  await page.route(productDetailPattern, async route => { await productGate; await route.continue(); });
  await page.goto(`${new URL(page.url()).origin}/seller/products/${product.id}/edit`, { waitUntil: 'domcontentloaded' });
  await page.locator('[aria-busy=true]').first().waitFor();
  await screenshot('commercial-product-loading.png');
  releaseProducts();
  await page.getByRole('heading', { name: 'Sửa sản phẩm', exact: true }).waitFor();
  await page.unroute(productDetailPattern);
  assert.equal(await page.locator('input[name=stock]').count(), 0);
  await checkout(2);
  await page.getByLabel('Tên sản phẩm', { exact: true }).fill('CommercialUI Cup Edited');
  await page.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
  await page.waitForURL('**/seller/products');
  assert.deepEqual(await stock(), { stock: 8, stockVersion: 1 });
  passed('T9 browser: saving product information from an old form preserves checkout stock');

  await goto(`/seller/products/${product.id}/edit`);
  const editor = page.getByRole('region', { name: 'Điều chỉnh tồn kho', exact: true });
  await editor.getByLabel('Tồn kho sau điều chỉnh', { exact: true }).fill('12');
  await editor.getByLabel('Lý do điều chỉnh', { exact: true }).fill('Synthetic UI verified physical count');
  await checkout(1);
  await editor.getByRole('button', { name: 'Lưu điều chỉnh tồn kho', exact: true }).click();
  await editor.getByRole('alert').filter({ hasText: 'Tồn kho đã thay đổi' }).waitFor();
  assert.equal((await stock()).stock, 7);
  await editor.getByRole('button', { name: 'Tải lại tồn kho', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('input[name=newStock]')?.value === '7');
  await editor.getByLabel('Tồn kho sau điều chỉnh', { exact: true }).fill('11');
  await editor.getByLabel('Lý do điều chỉnh', { exact: true }).fill('Synthetic UI verified recount after conflict');
  const pattern = `**/api/seller/products/${product.id}/stock`;
  let lost = false;
  await page.route(pattern, async route => {
    if (lost) return route.continue();
    lost = true;
    const response = await route.fetch(); assert.equal(response.status(), 200);
    await route.abort('failed');
  });
  await editor.getByRole('button', { name: 'Lưu điều chỉnh tồn kho', exact: true }).click();
  await editor.getByRole('alert').filter({ hasText: 'Chưa xác định kết quả' }).waitFor();
  assert.equal(await editor.getByLabel('Tồn kho sau điều chỉnh', { exact: true }).isDisabled(), true);
  await checkout(1);
  await editor.getByRole('button', { name: 'Thử lại điều chỉnh', exact: true }).click();
  await editor.getByText('Đã ghi nhận điều chỉnh. Tồn kho hiện tại: 10.', { exact: true }).waitFor();
  await page.unroute(pattern);
  assert.equal((await stock()).stock, 10);
  assert.equal((await database.query('SELECT count(*)::int AS n FROM product_stock_updates WHERE "productId"=$1', [product.id])).rows[0].n, 1);
  await page.setViewportSize({ width: 375, height: 812 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await screenshot('commercial-stock-mobile.png');
  await page.setViewportSize({ width: 1440, height: 1000 });
  passed('T9 browser: stale adjustment reloads safely; lost-response retry keeps a later checkout and writes one receipt; mobile fits');

  await page.route(productDetailPattern, route => route.fulfill({ status: 503, json: { message: 'Synthetic fixture outage' } }));
  await goto(`/seller/products/${product.id}/edit`);
  await page.getByRole('alert').filter({ hasText: 'Không thể tải sản phẩm' }).waitFor();
  await page.unroute(productDetailPattern);
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await page.getByRole('heading', { name: 'Sửa sản phẩm', exact: true }).waitFor();
  passed('T9 browser: product load failure offers a working retry');

  await goto('/products?search=CommercialUI&maxPrice=150000&sort=price_asc');
  const results = page.getByRole('region', { name: 'Kết quả sản phẩm', exact: true });
  assert.deepEqual(await results.getByRole('heading', { level: 3 }).allTextContents(), ['CommercialUI Cup Edited', 'CommercialUI Bowl']);
  await results.getByRole('article').first().getByText('100.000₫', { exact: true }).waitFor();
  await page.getByLabel('Giá đến', { exact: true }).fill('110000');
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await results.getByText('CommercialUI Bowl', { exact: true }).waitFor({ state: 'detached' });
  await results.getByRole('heading', { name: 'CommercialUI Cup Edited', exact: true }).waitFor();
  assert.equal(await results.getByRole('article').count(), 1);
  await page.getByLabel('Giá đến', { exact: true }).fill('150000');
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await results.getByText('CommercialUI Bowl', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: /^Sắp xếp/ }).selectOption('price_desc');
  await page.waitForFunction(() => document.querySelector('[aria-label="Kết quả sản phẩm"] h3')?.textContent === 'CommercialUI Bowl');
  await screenshot('commercial-effective-price.png');
  await logout(); await login(accounts.buyer);
  await goto(`/products/${product.id}`);
  await page.getByRole('button', { name: 'Mua ngay', exact: true }).click();
  await page.waitForURL('**/checkout');
  for (const [field, value] of Object.entries({ name: 'Synthetic UI buyer', phone: '0900000000', address: '1 Fixture Street', city: 'Hà Nội' })) await page.locator(`input[name=${field}]`).fill(value);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.includes('Đặt hàng an toàn') && !button.disabled));
  const beforeCheckout = (await database.query('SELECT count(*)::int AS n FROM orders WHERE "buyerId"=$1', [accounts.buyer.id])).rows[0].n;
  await page.getByRole('button', { name: 'Đặt hàng an toàn', exact: true }).click();
  await page.getByRole('heading', { name: 'Đặt hàng thành công', exact: true }).waitFor();
  const storedOrders = (await database.query('SELECT total FROM orders WHERE "buyerId"=$1 ORDER BY "createdAt" DESC', [accounts.buyer.id])).rows;
  assert.equal(storedOrders.length, beforeCheckout + 1);
  assert.equal(Number(storedOrders[0].total), 100000);
  passed('T11 browser: effective price controls visible order/filter, cart and real checkout total');

  const orderId = crypto.randomUUID();
  await database.query(`INSERT INTO orders(id,"buyerId","shopId",total,"shippingFee",status,"paymentMethod","paymentExpiresAt") VALUES($1,$2,$3,100000,25000,'pending','bank_transfer',CURRENT_TIMESTAMP+INTERVAL '30 minutes')`, [orderId, accounts.buyer.id, shopId]);
  await database.query('INSERT INTO order_items("orderId","productId",name,price,quantity) VALUES($1,$2,$3,100000,1)', [orderId, product.id, 'Commercial UI revenue fixture']);
  const { receipt } = await request('admin/payments/receipts', { orderId, reference: `UI-IN-${crypto.randomUUID()}`, amount: 125000, receivedAt: new Date().toISOString(), transferContent: 'Verified UI fixture', evidence: 'Synthetic verified bank receipt' });
  await request(`admin/payments/receipts/${receipt.id}/allocate`, { orderId, note: 'Verified fixture original bank payment' }, 'admin', 'post', 200);
  await database.query(`UPDATE orders SET status='delivered',"deliveredAt"=CURRENT_TIMESTAMP-INTERVAL '8 days' WHERE id=$1`, [orderId]);
  const route = `admin/settlements/shops/${shopId}`;
  await request(`${route}/policy`, { commissionBps: 500, note: 'Synthetic UI agreed commission five percent' });
  await request(`${route}/sync`, {}, 'admin', 'post', 200);
  await logout(); await login(accounts.seller);
  let releaseStats;
  const statsGate = new Promise(resolve => { releaseStats = resolve; });
  await page.route('**/api/seller/orders/stats', async route => { await statsGate; await route.continue(); });
  await page.goto(`${new URL(page.url()).origin}/seller/revenue`, { waitUntil: 'domcontentloaded' });
  await page.locator('[aria-busy=true]').first().waitFor();
  await screenshot('commercial-revenue-loading.png');
  releaseStats();
  await page.waitForLoadState('networkidle');
  await page.unroute('**/api/seller/orders/stats');
  const summary = page.getByRole('region', { name: 'Số liệu doanh thu và quyết toán', exact: true });
  const card = label => summary.locator('div').filter({ has: page.locator('p').filter({ hasText: new RegExp(`^${label}$`) }) }).last();
  await card('Hoa hồng theo sổ').getByText(/5\.000/, { exact: false }).waitFor();
  await card('Tiền ròng trong sổ').getByText(/95\.000/, { exact: false }).waitFor();
  await card('Khả dụng để lập kỳ').getByText(/95\.000/, { exact: false }).waitFor();
  await screenshot('commercial-seller-revenue.png');
  await summary.getByRole('link', { name: 'Xem sổ quyết toán và chứng từ', exact: true }).click();
  await page.getByRole('heading', { name: 'Quyết toán người bán', exact: true }).waitFor();
  await page.getByText(/95\.000/).first().waitFor();
  await page.route('**/api/seller/orders/stats', route => route.fulfill({ status: 503, json: { message: 'Synthetic fixture outage' } }));
  await goto('/seller/revenue');
  await page.getByRole('alert').filter({ hasText: 'Không thể tải dữ liệu doanh thu' }).waitFor();
  await page.unroute('**/api/seller/orders/stats');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await summary.waitFor();
  await card('Hoa hồng theo sổ').getByText(/5\.000/).waitFor();
  await page.setViewportSize({ width: 375, height: 812 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await screenshot('commercial-revenue-mobile.png');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await logout(); await login(accounts.admin); await goto('/admin');
  await card('Hoa hồng theo sổ').getByText(/5\.000/).waitFor();
  await screenshot('commercial-admin-revenue.png');
  await page.route('**/api/admin/stats', route => route.fulfill({ status: 503, json: { message: 'Synthetic fixture outage' } }));
  await goto('/admin');
  await page.getByRole('alert').filter({ hasText: 'Không thể tải thống kê admin' }).waitFor();
  assert.equal(await summary.count(), 0);
  await page.unroute('**/api/admin/stats');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await card('Hoa hồng theo sổ').getByText(/5\.000/).waitFor();
  passed('T10 browser: seller/admin show actual five-percent commission and settlement balance with failure/retry and mobile states');
}

module.exports = { verifyCommercialFixesUI };
