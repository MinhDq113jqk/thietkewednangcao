const assert = require('node:assert/strict');
const crypto = require('node:crypto');
async function verifyOperationsUI({ page, database, apiUrl, accounts, product, goto, login, logout, screenshot, passed, refreshSecret, password }) {
  await goto('/profile');
  await page.getByRole('button',{name:'Email và phiên đăng nhập',exact:true}).click();
  await page.getByText('Phiên hiện tại',{exact:false}).first().waitFor();
  const before=Number((await database.query('SELECT count(*) FROM auth_sessions WHERE "userId"=$1 AND "revokedAt" IS NULL',[accounts.buyer.id])).rows[0].count);
  // Separate HTTP context represents another device without changing browser cookies.
  const response=await fetch(`${apiUrl}/api/auth/login`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:accounts.buyer.email,password})});
  assert.equal(response.status,200);
  const otherData=await response.json();
  await page.reload();
  await page.getByRole('button',{name:'Email và phiên đăng nhập',exact:true}).click();
  const cards=page.locator('article').filter({hasNotText:'Phiên hiện tại'});
  const revoked=page.waitForResponse(r=>r.request().method()==='DELETE' && r.url().includes('/auth/sessions/'));
  await cards.first().getByRole('button',{name:'Thu hồi phiên',exact:true}).click();
  await revoked;
  const check=await fetch(`${apiUrl}/api/auth/me`,{headers:{Authorization:`Bearer ${otherData.token}`}});
  assert.equal(check.status,401);
  assert.equal(Number((await database.query('SELECT count(*) FROM auth_sessions WHERE "userId"=$1 AND "revokedAt" IS NULL',[accounts.buyer.id])).rows[0].count),before);
  await page.getByRole('button',{name:'Gửi email xác minh',exact:true}).click();
  await page.getByText('Hướng dẫn xác minh đã được đưa vào hàng chờ gửi.',{exact:true}).waitFor();
  const encrypted=(await database.query('SELECT payload FROM notification_outbox WHERE "userId"=$1 AND payload IS NOT NULL ORDER BY "createdAt" DESC LIMIT 1',[accounts.buyer.id])).rows[0].payload;
  const bytes=Buffer.from(encrypted,'base64');
  const decipher=crypto.createDecipheriv('aes-256-gcm',crypto.createHash('sha256').update(refreshSecret).digest(),bytes.subarray(0,12));
  decipher.setAuthTag(bytes.subarray(12,28));
  const privateData=JSON.parse(Buffer.concat([decipher.update(bytes.subarray(28)),decipher.final()]).toString());
  const actionUrl=new URL(privateData.href);
  await goto(actionUrl.pathname+actionUrl.hash);
  await page.getByRole('button',{name:'Xác minh email',exact:true}).click();
  await page.getByText('Đã xác minh email.',{exact:true}).waitFor();
  assert.equal(new URL(page.url()).hash,'');
  await screenshot('account-security.png');
  passed('Browser verifies encrypted email links and revokes another device without losing its current session');

  await goto('/support');
  await page.getByLabel('Tiêu đề',{exact:true}).fill('E2E support investigation');
  await page.getByLabel('Nội dung',{exact:true}).fill('Please inspect this synthetic request and respond.');
  await page.getByRole('button',{name:'Gửi yêu cầu',exact:true}).click();
  await page.getByRole('heading',{name:'E2E support investigation',exact:true}).waitFor();
  const ticket=(await database.query('SELECT id FROM support_tickets WHERE "requesterId"=$1 AND subject=$2',[accounts.buyer.id,'E2E support investigation'])).rows[0];
  await logout();await login(accounts.admin);await goto(`/admin/support?ticket=${ticket.id}`);
  await page.getByLabel('Phân công',{exact:true}).selectOption(accounts.admin.id);
  await page.getByLabel('Trạng thái mới',{exact:true}).selectOption('in_progress');
  await page.getByLabel('Lý do cập nhật',{exact:true}).fill('Assigned E2E customer support investigation');
  await page.getByRole('button',{name:'Lưu phân công và trạng thái',exact:true}).click();
  await page.getByText('Đang xử lý · Người phụ trách:',{exact:false}).waitFor();
  await page.getByLabel('Trả lời',{exact:true}).fill('E2E support response has been recorded.');
  await page.getByRole('button',{name:'Gửi phản hồi',exact:true}).click();
  await page.getByText('E2E support response has been recorded.',{exact:true}).waitFor();
  await screenshot('admin-support.png');
  await logout();await login(accounts.buyer);await goto(`/support?ticket=${ticket.id}`);
  await page.getByText('E2E support response has been recorded.',{exact:true}).waitFor();
  await goto('/notifications');await page.getByRole('heading',{name:'Phản hồi hỗ trợ mới',exact:true}).waitFor();
  await page.getByRole('button',{name:'Đánh dấu đã đọc',exact:true}).first().click();
  await screenshot('notifications.png');
  passed('Browser submits support, assigns an admin, replies and reads the resulting private notification');

  await logout();await login(accounts.admin);await goto('/admin/operations');
  await page.getByRole('button',{name:'Kiểm duyệt nội dung',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:product.id});
  await row.getByRole('button',{name:'Kiểm duyệt',exact:true}).click();
  await page.getByLabel('Lý do kiểm duyệt',{exact:true}).fill('E2E moderation private review reason');
  await page.getByRole('button',{name:'Ẩn nội dung',exact:true}).click();
  await row.getByText('Bị quản trị viên ẩn',{exact:true}).waitFor();
  assert.equal((await database.query('SELECT "moderationHidden" FROM products WHERE id=$1',[product.id])).rows[0].moderationHidden,true);
  await row.getByRole('button',{name:'Kiểm duyệt',exact:true}).click();
  await page.getByLabel('Lý do kiểm duyệt',{exact:true}).fill('E2E moderation approved after correction');
  await page.getByRole('button',{name:'Duyệt nội dung',exact:true}).click();
  await row.getByText('Được duyệt',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Nhật ký thao tác',exact:true}).click();
  await page.getByText('moderation_actions:',{exact:false}).first().waitFor();
  await screenshot('operations-audit.png');
  const notification=crypto.randomUUID();
  await database.query(`INSERT INTO notification_outbox(id,"userId",title,body,href,state,attempts) VALUES($1,$2,'E2E failed delivery','Synthetic delivery failure','/profile','failed',5)`,[notification,accounts.buyer.id]);
  await page.getByRole('button',{name:'Hàng chờ thông báo',exact:true}).click();
  await page.getByLabel('Trạng thái gửi',{exact:true}).selectOption('failed');
  await page.getByRole('row').filter({hasText:notification}).getByRole('button',{name:'Thử gửi lại',exact:true}).click();
  await page.getByText('Chưa có dữ liệu phù hợp.',{exact:true}).waitFor();
  assert.equal((await database.query('SELECT state,attempts FROM notification_outbox WHERE id=$1',[notification])).rows[0].state,'pending');
  passed('Browser records moderation reasons and immutable audit, then retries a failed notification without external delivery');

  // Enough equal-timestamp orders to force real server pages in both workspaces.
  const shop=(await database.query('SELECT "shopId" FROM products WHERE id=$1',[product.id])).rows[0].shopId;
  for(let i=0;i<23;i++) await database.query(`INSERT INTO orders("buyerId","shopId",total,status,"createdAt") VALUES($1,$2,1000,'pending','2026-10-20T17:30:00Z')`,[accounts.buyer.id,shop]);
  await logout();await login(accounts.seller);await goto('/seller/orders');
  await page.getByLabel('Từ ngày',{exact:true}).fill('2026-10-21');
  await page.getByLabel('Đến ngày',{exact:true}).fill('2026-10-21');
  await page.getByRole('navigation',{name:'Phân trang',exact:true}).getByRole('button',{name:'Trang sau',exact:true}).click();
  await page.getByText('Trang 2/',{exact:false}).waitFor();
  await page.getByLabel('Tìm đơn hàng',{exact:true}).fill('does-not-exist');
  await page.getByText('Không có đơn hàng phù hợp.',{exact:true}).waitFor();
  await logout();await login(accounts.buyer);await goto('/orders');
  await page.getByRole('button',{name:'Trang sau',exact:true}).click();
  await page.getByText('Trang 2/',{exact:false}).waitFor();
  await page.getByRole('tab',{name:'Chờ xác nhận',exact:true}).click();
  await page.getByText('Trang 1/',{exact:false}).waitFor();
  await screenshot('orders-pagination.png');
  let failOrders=true;
  const pattern='**/api/orders?**';
  await page.route(pattern, route=>failOrders ? route.abort('failed') : route.continue());
  await page.reload();
  await page.getByText('Không thể tải danh sách đơn hàng.',{exact:false}).waitFor();
  failOrders=false;
  await page.getByRole('button',{name:'Thử lại',exact:true}).click();
  await page.getByRole('button',{name:'Trang sau',exact:true}).waitFor({state:'visible'});
  await page.getByText('Không thể tải danh sách đơn hàng.',{exact:false}).waitFor({state:'hidden'});
  await page.unroute(pattern);
  await page.setViewportSize({width:390,height:844});await goto('/support');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await screenshot('support-mobile.png');await page.setViewportSize({width:1440,height:1000});
  passed('Buyer/seller browser pagination, filters, empty search, reset-to-first-page and mobile support layout use real API results');

  await logout();await goto('/forgot-password');
  await page.getByLabel('Email',{exact:true}).fill(accounts.other.email);
  await page.getByRole('button',{name:'Gửi hướng dẫn',exact:true}).click();
  await page.getByText('Nếu tài khoản hợp lệ, hướng dẫn sẽ được gửi qua email.',{exact:true}).waitFor();
  const resetRow=(await database.query('SELECT payload FROM notification_outbox WHERE "userId"=$1 AND payload IS NOT NULL ORDER BY "createdAt" DESC LIMIT 1',[accounts.other.id])).rows[0];
  const resetBytes=Buffer.from(resetRow.payload,'base64');
  const resetCipher=crypto.createDecipheriv('aes-256-gcm',crypto.createHash('sha256').update(refreshSecret).digest(),resetBytes.subarray(0,12));
  resetCipher.setAuthTag(resetBytes.subarray(12,28));
  const resetLink=new URL(JSON.parse(Buffer.concat([resetCipher.update(resetBytes.subarray(28)),resetCipher.final()]).toString()).href);
  await goto(resetLink.pathname+resetLink.hash);
  const newPassword=crypto.randomBytes(20).toString('base64url');
  await page.getByLabel('Mật khẩu mới',{exact:true}).fill(newPassword);
  await page.getByLabel('Xác nhận mật khẩu',{exact:true}).fill('different-password');
  await page.getByRole('button',{name:'Lưu mật khẩu mới',exact:true}).click();
  await page.getByText('Mật khẩu xác nhận chưa khớp.',{exact:true}).waitFor();
  await page.getByLabel('Xác nhận mật khẩu',{exact:true}).fill(newPassword);
  await page.getByRole('button',{name:'Lưu mật khẩu mới',exact:true}).click();
  await page.getByText('Đã đặt lại mật khẩu. Vui lòng đăng nhập lại.',{exact:true}).waitFor();
  await goto('/login');
  await page.locator('input[name=email]').fill(accounts.other.email);
  await page.locator('input[name=password]').fill(newPassword);
  await page.getByRole('button',{name:'Đăng nhập an toàn',exact:true}).click();
  await page.waitForURL(url=>url.pathname!=='/login');
  await logout();await login(accounts.buyer);
  passed('Browser recovery keeps validation errors, consumes the encrypted action link and accepts only the new password');
}
module.exports={verifyOperationsUI};
